// Radius of the residential balcony ring at angle theta (radians, atan2(z, x)).
// Samples sit on mid-bin angles from -π; vertices between them are linear.
export function petalRadius(tower, theta) {
  const n = tower.radii.length;
  let u = ((theta + Math.PI) / (Math.PI * 2)) * n - 0.5;
  u = ((u % n) + n) % n;
  const i = Math.floor(u) % n;
  const f = u - Math.floor(u);
  return tower.radii[i] * (1 - f) + tower.radii[(i + 1) % n] * f;
}

export function deckTop(level) {
  return LEVELS.parkStart + (level + 1) * LEVELS.parkPitch;
}

// 1 at an arch crown, 0 at a pier. Crowns are aligned to the petal phase.
export function archS(theta, phase) {
  const bay = (Math.PI * 2) / LEVELS.parkBays;
  const a = Math.atan2(Math.sin(theta - phase), Math.cos(theta - phase));
  return 0.5 + 0.5 * Math.cos((Math.PI * 2 * a) / bay);
}
