/** Same SW-NE diagonal as the app TIN, with north-positive grid rows. */
function heightFrom(grid,x,z) {
  const fx=(grid.ox+x*grid.s)/grid.step-grid.i0, fy=(grid.oy-z*grid.s)/grid.step-grid.j0;
  const i=Math.floor(fx),j=Math.floor(fy),a=fx-i,b=fy-j;
  if(i<0||j<0||i+1>=grid.heights[0].length||j+1>=grid.heights.length)throw new RangeError('Canada Olympic Park survey bounds');
  const h00=grid.heights[j][i],h10=grid.heights[j][i+1],h01=grid.heights[j+1][i],h11=grid.heights[j+1][i+1];
  return a>=b?(1-a)*h00+(a-b)*h10+b*h11:(1-b)*h00+(b-a)*h01+a*h11;
}
